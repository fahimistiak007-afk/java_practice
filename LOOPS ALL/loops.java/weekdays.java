public class weekdays {
    public static void main(String[] args) {
        int weeks=4;
        int counter=1;
        int days=7;
        for(int i=1;i<=weeks;i++){
            System.out.print("Week: " +i +":");
            for(int j=1;j<=days;j++){
            System.out.print(counter);
            counter++;
          
            }  
            System.out.println(" ");
        }
    }
    
}
